declare (strict_types=1);
use Sylius\Behat\Context\Api\Email_Context;
use Symfony\Component\Dependency_Injection\Loader\Configurator\Container_Configurator;
use function Symfony\Component\Dependency_Injection\Loader\Configurator\service;
return static function (Container_Configurator $container): void {
    $services = $container->services();
    $services->defaults()->public();
    $services->set('sylius.behat.context.api.email', Email_Context::class)->args([service('sylius.behat.shared_storage'), service('sylius.behat.email_checker'), service('translator')]);
};